const getInitialExpandedMenus = (tabs, activeTab) => {
    const expanded = {};
    tabs.forEach((tab) => {
        if (tab.submenu?.some((sub) => sub.id === activeTab)) {
            expanded[tab.id] = true;
        }
    });
    return expanded;
};

function MenuBadge({ count, className = '' }) {
    if (count === undefined || count <= 0) return null;
    return (
        <span
            className={`inline-flex min-h-5 min-w-5 shrink-0 items-center justify-center rounded-full bg-red-500 px-1.5 text-[11px] font-bold leading-none text-white ${className}`}
        >
            {count > 99 ? '99+' : count}
        </span>
    );
}

function MenuChevron({ expanded, className = '' }) {
    return (
        <svg
            className={`h-4 w-4 shrink-0 text-gray-400 transition-transform ${expanded ? 'rotate-90' : ''} ${className}`}
            fill="none"
            stroke="currentColor"
            viewBox="0 0 24 24"
            aria-hidden
        >
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9 5l7 7-7 7" />
        </svg>
    );
}

export default function ProfileMenuTabs({
    tabs,
    activeTab,
    onTabChange,
    badgeCounts = {},
    variant = 'sidebar',
    showAdminMenuSwitch = false,
    adminMenuMode,
    onAdminMenuModeChange,
    showSellerAutoserviceSwitch = false,
    sellerAutoserviceMode,
    onSellerAutoserviceModeChange,
}) {
    const isDrawer = variant === 'drawer';
    const [expandedMenus, setExpandedMenus] = useState(() =>
        getInitialExpandedMenus(tabs, activeTab)
    );

    useEffect(() => {
        setExpandedMenus((prev) => {
            const next = { ...prev };
            tabs.forEach((tab) => {
                if (tab.submenu?.some((sub) => sub.id === activeTab)) {
                    next[tab.id] = true;
                }
            });
            return next;
        });
    }, [activeTab, tabs]);

    const toggleSubmenu = (menuId) => {
        setExpandedMenus((prev) => ({
            ...prev,
            [menuId]: !prev[menuId],
        }));
    };

    const handleTabChange = (tabId) => {
        onTabChange(tabId);
        if (isDrawer) return;
        if (window.innerWidth < 1024) {
            setTimeout(() => {
                const mainContent = document.querySelector('main');
                if (mainContent) {
                    const headerOffset = 80;
                    const elementPosition = mainContent.getBoundingClientRect().top;
                    const offsetPosition = elementPosition + window.pageYOffset - headerOffset;
                    window.scrollTo({
                        top: offsetPosition,
                        behavior: 'smooth',
                    });
                } else {
                    window.scrollTo({ top: 0, behavior: 'smooth' });
                }
            }, 100);
        }
    };

    const handleSidebarItemClick = (event, tabId) => {
        const isPlainLeftClick = event.button === 0 && !event.metaKey && !event.ctrlKey && !event.shiftKey && !event.altKey;

        if (isDrawer) {
            // For drawer anchors we want SPA navigation on plain left click,
            // but keep default browser context-menu / "open in new tab" behavior.
            if (!isPlainLeftClick) return;
            event.preventDefault();
            handleTabChange(tabId);
            return;
        }

        // Keep native browser behavior for context menu / open in new tab.
        if (!isPlainLeftClick) return;
        event.preventDefault();
        handleTabChange(tabId);
    };

    const itemBase = isDrawer
        ? 'min-h-[44px] w-full rounded-xl px-3 py-3 text-left text-sm font-medium transition-colors flex items-center gap-3 active:scale-[0.99]'
        : 'mx-2 flex w-[calc(100%-1rem)] items-center gap-3 rounded-xl px-3 py-2.5 text-left text-sm font-medium transition-colors';

    const itemActive = isDrawer
        ? 'bg-gray-100 text-gray-900'
        : 'bg-gray-100 text-gray-900';

    const itemInactive = isDrawer
        ? 'text-gray-900 active:bg-gray-50'
        : 'text-gray-900 hover:bg-gray-50';

    const submenuItemBase = isDrawer
        ? 'min-h-[40px] w-full rounded-lg px-3 py-2.5 text-left text-sm font-medium transition-colors flex items-center gap-3 ml-2'
        : 'mx-2 flex w-[calc(100%-1rem)] items-center gap-3 rounded-xl py-2 pl-11 pr-3 text-left text-sm transition-colors';

    const renderMenuItem = (tab) => {
        if (tab.submenu) {
            const isExpanded = expandedMenus[tab.id];
            const hasActiveSubmenu = tab.submenu.some((subTab) => activeTab === subTab.id);

            return (
                <div key={tab.id} className={isDrawer ? 'mb-1' : ''}>
                    <button
                        type="button"
                        onClick={() => toggleSubmenu(tab.id)}
                        className={`${itemBase} ${hasActiveSubmenu ? itemActive : itemInactive}`}
                    >
                        <div className="flex min-w-0 flex-1 items-center gap-3">
                            <div className="shrink-0 text-gray-900">{getMenuIcon(tab.id)}</div>
                            <span
                                className={`min-w-0 flex-1 ${
                                    isDrawer ? 'break-words whitespace-normal' : 'whitespace-normal leading-snug'
                                }`}
                            >
                                {tab.label}
                            </span>
                        </div>
                        <MenuBadge count={badgeCounts[tab.id]} className="mr-1" />
                        <MenuChevron expanded={isExpanded} />
                    </button>
                    {isExpanded && (
                        <div className={isDrawer ? 'mt-1 space-y-0.5 pl-2' : 'mt-0.5 space-y-0.5'}>
                            {tab.submenu.map((subTab) => (
                                <a
                                    key={subTab.id}
                                    href={getPathForTab(subTab.id) || '#'}
                                    onClick={(event) => handleSidebarItemClick(event, subTab.id)}
                                    className={`${submenuItemBase} ${
                                        activeTab === subTab.id ? itemActive : itemInactive
                                    } ${activeTab === subTab.id ? 'font-medium' : 'font-normal text-gray-700'}`}
                                >
                                    {!isDrawer ? null : (
                                        <div className="shrink-0 text-gray-700">{getMenuIcon(subTab.id)}</div>
                                    )}
                                    <span
                                        className={`min-w-0 flex-1 ${
                                            isDrawer ? 'break-words whitespace-normal' : 'whitespace-normal leading-snug'
                                        }`}
                                    >
                                        {subTab.label}
                                    </span>
                                    <MenuBadge count={badgeCounts[subTab.id]} />
                                </a>
                            ))}
                        </div>
                    )}
                </div>
            );
        }

        return (
            <a
                key={tab.id}
                href={getPathForTab(tab.id) || '#'}
                onClick={(event) => handleSidebarItemClick(event, tab.id)}
                className={`${itemBase} ${activeTab === tab.id ? itemActive : itemInactive} ${
                    isDrawer ? 'mb-1' : ''
                }`}
            >
                <div className="shrink-0 text-gray-900">{getMenuIcon(tab.id)}</div>
                <span
                    className={`min-w-0 flex-1 ${
                        isDrawer ? 'break-words whitespace-normal' : 'whitespace-normal leading-snug'
                    }`}
                >
                    {tab.label}
                </span>
                <MenuBadge count={badgeCounts[tab.id]} className="ml-auto" />
            </a>
        );
    };

    if (isDrawer) {
        return (
            <div className="flex flex-col gap-0.5 pb-20">
                {showAdminMenuSwitch ? (
                    <AdminMenuModeSwitch
                        variant="drawer"
                        mode={adminMenuMode}
                        onChange={onAdminMenuModeChange}
                    />
                ) : null}
                {showSellerAutoserviceSwitch ? (
                    <SellerAutoserviceModeSwitch
                        variant="drawer"
                        mode={sellerAutoserviceMode}
                        onChange={onSellerAutoserviceModeChange}
                    />
                ) : null}
                {tabs.map(renderMenuItem)}
            </div>
        );
    }

    return (
        <div
            className="sticky top-[calc(var(--sg-desktop-header-h)+1rem)] max-h-[calc(100dvh-var(--sg-desktop-header-h)-2rem)] w-full min-w-[15.5rem] overflow-y-auto overscroll-contain scroll-pb-32 bg-white [&::-webkit-scrollbar]:hidden"
            style={{ scrollbarWidth: 'none', msOverflowStyle: 'none' }}
        >
            {showAdminMenuSwitch ? (
                <AdminMenuModeSwitch
                    variant="sidebar"
                    mode={adminMenuMode}
                    onChange={onAdminMenuModeChange}
                />
            ) : null}
            {showSellerAutoserviceSwitch ? (
                <SellerAutoserviceModeSwitch
                    variant="sidebar"
                    mode={sellerAutoserviceMode}
                    onChange={onSellerAutoserviceModeChange}
                />
            ) : null}
            <nav className="flex flex-col gap-0.5 py-2">{tabs.map(renderMenuItem)}</nav>
            <PublicSiteMenuLinks variant="sidebar" />
        </div>
    );
}
